def upsert_to_supabase(data):
    if not SUPABASE_URL or not SUPABASE_KEY:
        print("Missing Supabase credentials in .env")
        return
        
    headers = {
        'apikey': SUPABASE_KEY,
        'Authorization': f'Bearer {SUPABASE_KEY}',
        'Content-Type': 'application/json',
        'Prefer': 'resolution=merge-duplicates'
    }
    
    url = f"{SUPABASE_URL}/rest/v1/player_opportunities_challenges"
    
    print(f"Upserting {len(data)} records to Supabase...")
    response = requests.post(url, headers=headers, json=data)
    
    if response.status_code in [200, 201]:
        print("Successfully upserted advanced metrics!")
    else:
        print(f"Failed to upsert: {response.status_code} - {response.text}")

